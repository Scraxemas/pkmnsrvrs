export function frameGroundOffset(species:string,frameIndex:number){
  const metadata=SPRITE_FRAMES[species],rows=FRAME_BOTTOM_PADDING[species];
  if(!metadata||!rows)return 0;
  const row=Math.max(0,Math.min(7,Math.floor(frameIndex/metadata.frames)));
  const column=Math.max(0,Math.min(metadata.frames-1,frameIndex%metadata.frames));
  return rows[row]?.[column]??0;
}


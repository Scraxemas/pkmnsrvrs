"""Import ancestry metadata only; this does not create playable species or art."""
import csv
import hashlib
import io
import json
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'data/v2/csv/pokemon_species.csv'

def fetch(url):
    with urlopen(Request(url, headers={'User-Agent': 'Pokemon-Survivors-data-import'}), timeout=30) as response:
        return response.read()

revision = json.loads(fetch('https://api.github.com/repos/PokeAPI/pokeapi/commits?path=' + SOURCE + '&per_page=1'))[0]['sha']
base = f'https://raw.githubusercontent.com/PokeAPI/pokeapi/{revision}/'
data = fetch(base + SOURCE)
rows = list(csv.DictReader(io.StringIO(data.decode('utf-8'))))
parents = [(int(row['id']), int(row['evolves_from_species_id'])) for row in rows if row['evolves_from_species_id']]
archive = ROOT / 'assets/data/pokeapi'
archive.mkdir(parents=True, exist_ok=True)
(archive / 'pokemon_species.csv').write_bytes(data)
for filename in ('LICENSE.md', 'LICENSE'):
    try:
        (archive / filename).write_bytes(fetch(base + filename))
        break
    except HTTPError as error:
        if error.code != 404:
            raise
else:
    raise RuntimeError('Upstream license was not found')
provenance = {'repository': 'https://github.com/PokeAPI/pokeapi', 'revision': revision, 'source': SOURCE,
              'sha256': hashlib.sha256(data).hexdigest(), 'use': 'Evolution ancestry only; no gameplay definitions or artwork',
              'species': len(rows), 'parentLinks': len(parents)}
(archive / 'source.json').write_text(json.dumps(provenance, indent=2) + '\n', encoding='utf-8')
output = ROOT / 'src/data/evolutionParents.ts'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('// Generated by tools/import_evolution_families.py.\n'
                  f'// PokeAPI/pokeapi {revision}; attribution in assets/data/pokeapi.\n'
                  '// [species National Dex ID, immediate pre-evolution National Dex ID].\n'
                  'export const EVOLUTION_PARENTS:readonly (readonly [number,number])[]=[\n'
                  + ''.join(f'  [{dex},{parent}],\n' for dex, parent in parents) + '];\n', encoding='utf-8')
print(json.dumps(provenance))
